public static int Apply(string path,MapDocument source,MapDocument target,ClientAssets assets,out int anchors,out int roofPieces,out int skippedRoofs) {
 anchors=0;roofPieces=0;skippedRoofs=0;var pending=new List<StaticPlacement>();var checkedIds=new HashSet<int>();
 using(var raw=new Bitmap(path))using(var image=new Bitmap(raw.Width,raw.Height,PixelFormat.Format32bppArgb)) {
 if(raw.Width!=source.Width||raw.Height!=source.Height)throw new InvalidDataException("Decorations.png dimensions must match terrain and heightmap exactly.");
 using(var g=Graphics.FromImage(image)){g.CompositingMode=System.Drawing.Drawing2D.CompositingMode.SourceCopy;g.DrawImageUnscaled(raw,0,0);}
 var data=image.LockBits(new Rectangle(0,0,image.Width,image.Height),ImageLockMode.ReadOnly,PixelFormat.Format32bppArgb);
 try {var row=new int[image.Width];for(int y=0;y<image.Height;y++){Marshal.Copy(IntPtr.Add(data.Scan0,y*data.Stride),row,0,row.Length);for(int x=0;x<row.Length;x++){
 int rgb=row[x]&0xffffff; if((uint)row[x]>>24!=255)throw new InvalidDataException("Transparent decoration pixel at "+x+","+y);
 if(rgb==0)continue;int[] ids;if(!Palette.TryGetValue(rgb,out ids))throw new InvalidDataException("Unknown exact decoration color #"+rgb.ToString("X6")+" at "+x+","+y);
 int i=y*source.Width+x;if(source.Materials[i]==18)throw new InvalidDataException("Decoration on forbidden rock terrain at "+x+","+y+". Remove it in the editor.");
 anchors++;foreach(int id in ids){if(checkedIds.Add(id)&&!assets.HasStaticArt(id))throw new InvalidDataException("Missing decoration artwork "+id);
 if((long)target.Statics.Count+pending.Count>=MapDocument.MaximumStatics)throw new InvalidDataException("Decoration static limit exceeded.");
 pending.Add(new StaticPlacement{X=x,Y=y,Z=source.Elevation[i],Id=(ushort)id,Hue=0});}
 }}}finally{image.UnlockBits(data);}
 }roofPieces=AddRoofs(source,pending,assets,out skippedRoofs);if((long)target.Statics.Count+pending.Count>MapDocument.MaximumStatics)throw new InvalidDataException("Decoration/roof static limit exceeded.");target.Statics.AddRange(pending);return pending.Count;
}
static int AddRoofs(MapDocument source,List<StaticPlacement> pieces,ClientAssets assets,out int skipped) {
 skipped=0;int w=source.Width,h=source.Height,count=0;var walls=new bool[w*h];var seen=new bool[w*h];foreach(var p in pieces)if(p.Id==130)walls[p.Y*w+p.X]=true;
 int wallHeight=assets.StaticHeight(130);if(wallHeight<=0)throw new InvalidDataException("Stone wall has invalid height metadata.");
 for(int start=0;start<w*h;start++)if(walls[start]&&!seen[start]){
 var queue=new List<int>{start};seen[start]=true;int x0=w,y0=h,x1=0,y1=0;
 for(int q=0;q<queue.Count;q++){int i=queue[q],x=i%w,y=i/w;x0=Math.Min(x0,x);x1=Math.Max(x1,x);y0=Math.Min(y0,y);y1=Math.Max(y1,y);foreach(int n in new[]{x>0?i-1:-1,x+1<w?i+1:-1,y>0?i-w:-1,y+1<h?i+w:-1})if(n>=0&&walls[n]&&!seen[n]){seen[n]=true;queue.Add(n);}}
 int z=source.Elevation[start],roofZ=z+wallHeight;bool okay=x1-x0>=2&&y1-y0>=2&&queue.Count==2*(x1-x0+y1-y0)&&roofZ<=127;
 for(int y=y0;y<=y1&&okay;y++)for(int x=x0;x<=x1;x++){int i=y*w+x;bool edge=x==x0||x==x1||y==y0||y==y1;if(source.Materials[i]!=39||source.Elevation[i]!=z||walls[i]!=edge){okay=false;break;}}
 if(!okay){skipped++;continue;}if(!assets.HasStaticArt(1306))throw new InvalidDataException("Missing flat stone roof artwork1306");
 for(int y=y0;y<=y1;y++)for(int x=x0;x<=x1;x++){pieces.Add(new StaticPlacement{X=x,Y=y,Z=(sbyte)roofZ,Id=1306,Hue=0});count++;}
 }return count;
}
